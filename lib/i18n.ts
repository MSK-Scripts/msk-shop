export type AdminCopy = typeof adminEn

export const adminTranslations: { en: AdminCopy } & Partial<Record<Lang, AdminCopy>> = { en: adminEn }

/** Copy of the admin in `lang`, English where that language has none yet. */
export function adminCopy(lang: Lang): AdminCopy {
  return adminTranslations[lang] ?? adminTranslations.en
}

/**
 * The language the admin speaks on a page in `lang`: `lang` once the admin
 * has copy for it, English until then. Dates and numbers follow it, so the
 * English admin under `/de/admin` does not show German dates.
 */
export function adminLang(lang: Lang): Lang {
  return adminTranslations[lang] ? lang : 'en'
}

/** An admin string with its `{name}` placeholders filled. */
export function fillCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match))
}
